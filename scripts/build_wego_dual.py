def look_at_xyaxes(pos, target):
    f = np.asarray(target, float) - pos
    f /= np.linalg.norm(f)
    right = np.cross(f, [0, 0, 1.0])
    right /= np.linalg.norm(right)
    return [*right, *np.cross(right, f)]                       # MuJoCo 카메라: x 오른쪽, y 위, -z 시선


def build_scene(arm: mujoco.MjSpec, fits: dict, mount_files: list, head_pos, lift: float, spacer):
    """lift: 받침(CAD 바닥면)을 테이블 위로 올리는 높이. spacer: (cx, cy, hx, hy) 받침 아래 가정 판."""
    s = mujoco.MjSpec.from_string(SCENE)
    s.modelfiledir = str(OUT)
    wb = s.worldbody
    z0 = TABLE_TOP + lift
    # 테이블: 로봇은 뒤쪽 끝, 앞으로 작업 공간
    wb.add_geom(name="table", type=mujoco.mjtGeom.mjGEOM_BOX, size=[0.50, 0.60, TABLE_TOP / 2],
                pos=[0.30, 0, TABLE_TOP / 2], material="table")
    for i, f in enumerate(mount_files):                       # 빈 리스트면 토르소 없음 (팔만)
        s.add_mesh(name=f"wego_mount_{i}", file=f)
        wb.add_geom(name=f"wego_mount_{i}", type=mujoco.mjtGeom.mjGEOM_MESH, meshname=f"wego_mount_{i}",
                    material="mount", pos=[0, 0, z0], contype=0, conaffinity=0, group=1)
    if lift > 0 and mount_files:      # CAD 에 없는 받침판 (가정): 팔 베이스는 테이블 위, 받침 블록은 이 판 위
        cx, cy, hx, hy = spacer
        wb.add_geom(name="mount_spacer_assumed", type=mujoco.mjtGeom.mjGEOM_BOX, size=[hx, hy, lift / 2],
                    pos=[cx, cy, TABLE_TOP + lift / 2], rgba=[0.3, 0.32, 0.35, 1], contype=0, conaffinity=0)
    cam_pos = np.array([head_pos[0], head_pos[1], head_pos[2] + z0])
    wb.add_camera(name="head", pos=cam_pos, xyaxes=look_at_xyaxes(cam_pos, [0.38, 0, TABLE_TOP]), fovy=42.0)
    colors = [[0.9, 0.3, 0.2, 1], [0.2, 0.5, 0.9, 1], [0.2, 0.75, 0.35, 1]]
    for i, (y, c) in enumerate(zip([-0.12, 0.0, 0.12], colors)):
        b = wb.add_body(name=f"cube{i}", pos=[0.38, y, TABLE_TOP + 0.0251])
        b.add_freejoint()
        b.add_geom(type=mujoco.mjtGeom.mjGEOM_BOX, size=[0.025] * 3, rgba=c, mass=0.08, condim=4,
                   friction=[1.0, 0.02, 0.001])
    tgt = wb.add_body(name="target", mocap=True, pos=[0.38, 0, TABLE_TOP + 0.2])
    tgt.add_geom(type=mujoco.mjtGeom.mjGEOM_SPHERE, size=[0.012], rgba=[0.2, 0.9, 0.4, 0.5],
                 contype=0, conaffinity=0)
    for side, f in fits.items():
        fr = wb.add_frame(pos=[f["base_pos"][0], f["base_pos"][1], f["base_pos"][2] + z0],
                          quat=f["base_quat"])
        s.attach(arm.copy(), prefix=f"{side}_", frame=fr)
    return s


HOME_GRIPPER = 0.03      # [m] 홈에서 손가락 하나당 열림 (최대 0.05)


def add_home_key(scene: mujoco.MjSpec) -> None:
    """키프레임 'home': 팔 관절 = configs/nero_dual.yaml 의 arms.<side>.home_q (값은 config 한 곳에서만 관리)."""
    import yaml
    arms = yaml.safe_load((ROOT / "configs/nero_dual.yaml").read_text(encoding="utf-8"))["arms"]
    m = scene.compile()
    d = mujoco.MjData(m)
    for side, acfg in arms.items():
        for j, q in zip(acfg["joints"], acfg["home_q"]):
            d.qpos[m.joint(j).qposadr[0]] = q
            d.ctrl[m.actuator(j).id] = q                       # 액추에이터 이름 = 관절 이름
        for j in acfg["gripper_joints"]:
            lo, hi = m.joint(j).range
            d.qpos[m.joint(j).qposadr[0]] = HOME_GRIPPER * np.sign(hi if abs(hi) >= abs(lo) else lo)
        d.ctrl[m.actuator(acfg["gripper_actuator"]).id] = HOME_GRIPPER
    scene.add_key(name="home", qpos=d.qpos.tolist(), ctrl=d.ctrl.tolist())


# ============================================================================ main
def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--nero-dir", default=str(ROOT.parent / "agx_arm_sim/mujoco/agilex_arm/agilex_nero"))
    p.add_argument("--wego-stl", default=os.path.expandvars(
        r"%USERPROFILE%/Desktop/ImageToStl.com_WeGo_Nero_Dual+Arm/WeGo_Nero_Dual Arm.stl"))
    p.add_argument("--cad-height", action="store_true",
                   help="CAD 높이 그대로 (받침 바닥 = 테이블, 팔 베이스는 테이블 속 76mm). 기본: 팔 베이스 = 테이블")
    p.add_argument("--with-torso", action="store_true",
                   help="WeGo 받침(토르소) 메쉬를 장면에 포함 (기본: 팔만)")
    p.add_argument("--keep-cad-torso", action="store_true",
                   help="받침(토르소)을 CAD 방향 그대로 (기본: 위아래 뒤집어 로고가 바로 서게)")
    a = p.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    # ---------------------------------------------------------------- 1) STL → world
    V, F, comp = split_components(read_stl(Path(a.wego_stl)))
    V = V @ R_WORLD_STL.T / 1000.0
    lo, hi = V.min(0), V.max(0)
    V -= [(lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2, lo[2]]            # 임시 원점: bbox 중심, 바닥 z=0
    print(f"STL: {len(F)} faces, {comp.max() + 1} 부품, 크기 {np.round(hi - lo, 3)} m")

    # ---------------------------------------------------------------- 2) 팔 정합
    arm = load_arm_spec(Path(a.nero_dir))
    tip = add_tcp_site(arm)
    sampler = ArmSampler(arm)
    fits = {}
    for side, ysign in [("left", 1.0), ("right", -1.0)]:
        side_pts = V[V[:, 1] * ysign > 0.12]                            # 해당 쪽
        upper = side_pts[side_pts[:, 2] > 0.4]                          # 팔 위쪽 링크 → 수직 중심선
        xc, yc = float(np.median(upper[:, 0])), float(np.median(upper[:, 1]))
        near = np.hypot(side_pts[:, 0] - xc, side_pts[:, 1] - yc) < 0.11   # 기둥·다른 부품 제외
        tree = cKDTree(side_pts[near])
        x, res = fit_arm(sampler, tree, [xc, yc, -0.07], side)
        R = Rotation.from_rotvec(x[:3])
        q_wxyz = np.roll(R.as_quat(), 1)
        _, owner = sampler.points(x[6:13], x[13])
        owner = owner[~np.isin(owner, [sampler.m.body(n).id for n in ("base_link", "link1")])]
        per_body = {sampler.m.body(b).name: round(float(np.median(res[owner == b])) * 1000, 2)
                    for b in np.unique(owner)}
        fits[side] = {"base_pos": x[3:6].tolist(), "base_quat": q_wxyz.tolist(),
                      "base_rpy_deg": R.as_euler("xyz", degrees=True).round(2).tolist(),
                      "q_cad": np.round(x[6:13], 4).tolist(), "gripper_cad": round(float(x[13]), 4),
                      "median_mm": round(float(np.median(res)) * 1000, 2),
                      "p90_mm": round(float(np.percentile(res, 90)) * 1000, 2), "per_body_median_mm": per_body}
        print(f"  {side}: base {np.round(x[3:6], 4)} rpy {fits[side]['base_rpy_deg']} "
              f"q {fits[side]['q_cad']}  잔차 median {fits[side]['median_mm']} / p90 {fits[side]['p90_mm']} mm")

    # 원점을 두 팔 베이스 중점(바닥 높이)으로 다시 잡기
    c = (np.array(fits["left"]["base_pos"]) + np.array(fits["right"]["base_pos"])) / 2
    c[2] = 0.0
    V -= c
    for f in fits.values():
        f["base_pos"] = (np.array(f["base_pos"]) - c).round(5).tolist()

    # ---------------------------------------------------------------- 3) 받침 = 팔 표면에서 먼 부품
    arm_pts = []
    for f in fits.values():
        P, own = sampler.points(np.array(f["q_cad"]), f["gripper_cad"], dense=True)
        P = P[~np.isin(own, [sampler.m.body(n).id for n in ("base_link", "link1")])]   # CAD 에 없는 부분
        R = Rotation.from_quat(np.roll(f["base_quat"], -1)).as_matrix()
        arm_pts.append(P @ R.T + f["base_pos"])
    arm_tree = cKDTree(np.concatenate(arm_pts))
    # 받침 = 팔 표면에서 멀고, 팔 축 근처 어깨 위쪽(움직이는 부분)도 아닌 부품.
    # 두 번째 조건: CAD 의 100mm 그리퍼 몸체처럼 공식 메쉬와 모양이 달라 거리로는 안 걸리는 팔 부품 제외
    axes_xy = np.array([f["base_pos"][:2] for f in fits.values()])
    z_shoulder = max(f["base_pos"][2] for f in fits.values()) + 0.20       # 베이스 바닥 + 20cm 위부터 팔
    mount = np.zeros(comp.max() + 1, bool)
    for ci in range(comp.max() + 1):
        vi = np.unique(F[comp == ci])
        P = V[vi]
        dist, _ = arm_tree.query(P[:: max(1, len(vi) // 200)])
        on_arm = (P[:, 2].min() > z_shoulder and
                  np.min(np.linalg.norm(axes_xy - P[:, :2].mean(0), axis=1)) < 0.10)
        mount[ci] = np.median(dist) > 0.004 and not on_arm

    # 받침(토르소)만 위아래 뒤집기: CAD 에서 받침은 팔과 반대 방향으로 들어가 있음 (로고 글자가 거꾸로).
    # 앞뒤 축(x) 기준 180° 회전 → 로고는 계속 앞(+x)을 보고 바로 섬. 바닥 높이·좌우 중심은 유지.
    if not a.keep_cad_torso:
        vi = np.unique(F[mount[comp]])
        lo_m, hi_m = V[vi].min(0), V[vi].max(0)
        cy, cz = (lo_m[1] + hi_m[1]) / 2, (lo_m[2] + hi_m[2]) / 2
        V[vi, 1] = 2 * cy - V[vi, 1]
        V[vi, 2] = 2 * cz - V[vi, 2]
    # MuJoCo STL 한도(20만 면) → 부품 단위로 나눠 여러 파일
    mount_files, chunk, n_chunk = [], [], 0
    ids = [ci for ci in np.argsort(-np.bincount(comp)) if mount[ci]]
    for i, ci in enumerate(ids):
        chunk.append(ci)
        n_chunk += int((comp == ci).sum())
        if i == len(ids) - 1 or n_chunk + int((comp == ids[i + 1]).sum()) > 190_000:
            Fm = F[np.isin(comp, chunk)]
            used, Fi = np.unique(Fm, return_inverse=True)
            name = f"wego_mount_{len(mount_files)}.stl"
            write_stl(OUT / name, V[used], Fi.reshape(-1, 3))
            mount_files.append(name)
            chunk, n_chunk = [], 0
    for old in OUT.glob("wego_mount*.stl"):
        if old.name not in mount_files:
            old.unlink()
    Vm = V[np.unique(F[mount[comp]])]
    print(f"받침: {mount.sum()}/{len(mount)} 부품, {int(mount[comp].sum())} faces → {mount_files}")

    # 머리 카메라: 상판(가장 높은 받침 부품) 앞 끝 위, 작업 영역(큐브 위치)을 바라봄
    center = Vm[np.abs(Vm[:, 1]) < 0.15]                                # 가운데 기둥 영역
    top = center[center[:, 2] > center[:, 2].max() - 0.01]               # 상판
    head_pos = [float(top[:, 0].max()) + 0.02, 0.0, float(center[:, 2].max()) + 0.04]

    # CAD 에서는 팔 베이스 바닥이 받침 바닥보다 아래 (CAD 에 베이스 형상 없음).
    # 기본: 팔 베이스를 테이블 위에 두고 받침은 그 높이차만큼의 판(가정) 위에 올림
    lift = 0.0 if a.cad_height else -min(f["base_pos"][2] for f in fits.values())
    foot = Vm[Vm[:, 2] < 0.005]
    spacer = ((foot[:, 0].min() + foot[:, 0].max()) / 2, (foot[:, 1].min() + foot[:, 1].max()) / 2,
              (foot[:, 0].max() - foot[:, 0].min()) / 2, (foot[:, 1].max() - foot[:, 1].min()) / 2)
    print(f"받침 높이 보정: {lift * 1000:.1f} mm ({'CAD 그대로' if a.cad_height else '팔 베이스 = 테이블 면'})")

    # ---------------------------------------------------------------- 4) 장면
    scene = build_scene(arm, fits, mount_files if a.with_torso else [], head_pos, lift, spacer)
    add_home_key(scene)
    m = scene.compile()
    xml = scene.to_xml()
    (OUT / "nero_dual.xml").write_text(xml, encoding="utf-8")
    m2 = mujoco.MjModel.from_xml_path(str(OUT / "nero_dual.xml"))
    assert m2.nq == m.nq and m2.nu == m.nu
    info = {"source_stl": Path(a.wego_stl).name, "table_top": TABLE_TOP, "mount_lift": lift,
            "tcp_from_link7_x": tip - 0.015, "head_camera_pos_rel_mount": head_pos, "arms": fits}
    (OUT / "wego_fit.json").write_text(json.dumps(info, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"assets/nero/nero_dual.xml: nq={m2.nq} nu={m2.nu} neq={m2.neq} "
          f"actuators={[m2.actuator(i).name for i in range(m2.nu)]}")


if __name__ == "__main__":
    main()
