# ============================================================================ STL
def read_stl(path: Path) -> np.ndarray:
    b = path.read_bytes()
    n = struct.unpack("<I", b[80:84])[0]
    if 84 + 50 * n != len(b):
        raise ValueError("binary STL 만 지원")
    a = np.frombuffer(b[84:84 + 50 * n], dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]))
    return a["v"].astype(np.float64)


def split_components(tri: np.ndarray):
    key = np.round(tri.reshape(-1, 3) / 1e-3).astype(np.int64)
    uniq, inv = np.unique(key, axis=0, return_inverse=True)
    F = inv.reshape(-1, 3)
    V = uniq * 1e-3
    e = np.concatenate([F[:, [0, 1]], F[:, [1, 2]], F[:, [2, 0]]])
    g = coo_matrix((np.ones(len(e)), (e[:, 0], e[:, 1])), shape=(len(V), len(V)))
    _, lab = connected_components(g, directed=False)
    return V, F, lab[F[:, 0]]


def write_stl(path: Path, V: np.ndarray, F: np.ndarray) -> None:
    tri = V[F].astype(np.float32)
    n = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    n /= np.maximum(np.linalg.norm(n, axis=1, keepdims=True), 1e-12)
    rec = np.zeros(len(F), dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]))
    rec["n"], rec["v"] = n, tri
    path.write_bytes(b"wego mount (generated by build_wego_dual.py)".ljust(80, b" ")
                     + struct.pack("<I", len(F)) + rec.tobytes())


