def load_arm_spec(nero_dir: Path) -> mujoco.MjSpec:
    """공식 nero.xml 사본 → 장면용으로 정리한 spec."""
    dst = OUT / "agilex_nero"
    (dst / "assets").mkdir(parents=True, exist_ok=True)
    src_xml = nero_dir / "nero.xml"
    shutil.copy2(src_xml, dst / "nero.xml")
    spec = mujoco.MjSpec.from_file(str(dst / "nero.xml"))
    for m in spec.meshes:                                      # 실제로 쓰는 메쉬만 복사
        shutil.copy2(nero_dir / "assets" / m.file, dst / "assets" / m.file)
        m.file = f"agilex_nero/assets/{m.file}"
    spec.meshdir = ""
    spec.modelfiledir = str(OUT)                               # 메쉬 경로 기준 = assets/nero

    for k in list(spec.keys):                                  # 장면 qpos 크기가 달라지므로 키프레임 제거
        spec.delete(k)
    for b in spec.bodies:
        if b.name != "world":
            b.gravcomp = 1.0                                   # 실제 팔의 중력 보상 제어 흉내
    link_bodies = {"base_link", *[f"link{i}" for i in range(1, 8)]}
    for g in spec.geoms:
        body = g.parent.name
        if g.contype == 0 and g.conaffinity == 0:              # 시각화 geom
            continue
        if body in link_bodies:                                # 링크 충돌은 끔 (IK 가 충돌을 모르므로 teleop 방해)
            g.contype, g.conaffinity, g.group = 0, 0, 3
            g.rgba = [0, 0, 0, 0]
        else:                                                  # 손가락: 물체 집기용 충돌 유지
            g.condim, g.friction = 4, [1.5, 0.02, 0.001]
            g.group = 3
            g.rgba = [0, 0, 0, 0]
    gm = spec.material("gripper_gray")
    for g in spec.geoms:                                       # 공식 파일에서 재질 없는 그리퍼 시각 geom
        if g.group == 1 and not g.material and g.parent.name.startswith(("gripper", "link7")):
            g.material = gm.name
    for a in spec.actuators:
        if a.name in ARM_JOINTS:
            kp = ARM_KP[ARM_JOINTS.index(a.name)]
            a.gainprm[0], a.biasprm[1], a.biasprm[2] = kp, -kp, -ARM_KV_RATIO * kp
    return spec


def add_tcp_site(spec: mujoco.MjSpec) -> float:
    """손가락 끝 사이 TCP site (link7 기준). z = 접근(link7 +x), y = 손가락 열림(link7 +z)."""
    m = spec.compile()
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    b7 = m.body("link7").id
    R7, p7 = d.xmat[b7].reshape(3, 3), d.xpos[b7]
    tip = -np.inf
    for gi in range(m.ngeom):
        if m.geom_group[gi] != 1 or m.body(m.geom_bodyid[gi]).name not in ("gripper_link1", "gripper_link2"):
            continue
        mid = m.geom_dataid[gi]
        v = m.mesh_vert[m.mesh_vertadr[mid]: m.mesh_vertadr[mid] + m.mesh_vertnum[mid]]
        vw = v @ d.geom_xmat[gi].reshape(3, 3).T + d.geom_xpos[gi]
        tip = max(tip, float(((vw - p7) @ R7)[:, 0].max()))
    R_site = np.array([[0, 0, 1], [1, 0, 0], [0, 1, 0]], float)     # 열 = site x,y,z 를 link7 축으로
    q = np.zeros(4)
    mujoco.mju_mat2Quat(q, R_site.reshape(-1))
    spec.body("link7").add_site(name="tcp", pos=[tip - 0.015, 0, -0.0235], quat=q, size=[0.004] * 3,
                                rgba=[1, 0.2, 0.2, 0.7], group=2)
    return tip


class ArmSampler:
    """단팔 모델: 관절값 → 시각 메쉬 점들(베이스 좌표)."""

    def __init__(self, spec: mujoco.MjSpec, per_body: int = 500, seed: int = 0):
        self.m = spec.compile()
        self.d = mujoco.MjData(self.m)
        rng = np.random.default_rng(seed)
        self.items = []                                       # (body id, geom id, local pts in geom frame)
        for gi in range(self.m.ngeom):
            if self.m.geom_group[gi] != 1 or self.m.geom_type[gi] != mujoco.mjtGeom.mjGEOM_MESH:
                continue
            mid = self.m.geom_dataid[gi]
            v = self.m.mesh_vert[self.m.mesh_vertadr[mid]: self.m.mesh_vertadr[mid] + self.m.mesh_vertnum[mid]]
            idx = rng.choice(len(v), min(per_body, len(v)), replace=False)
            self.items.append((gi, v[idx].astype(float), v.astype(float)))
        self.qadr = [self.m.joint(n).qposadr[0] for n in ARM_JOINTS]
        self.gadr = [self.m.joint(n).qposadr[0] for n in ("gripper_joint1", "gripper_joint2")]

    def points(self, q, g, dense=False):
        self.d.qpos[:] = 0
        self.d.qpos[self.qadr] = q
        self.d.qpos[self.gadr] = [g, -g]
        mujoco.mj_kinematics(self.m, self.d)
        out, owner = [], []
        for gi, sparse, full in self.items:
            P = full if dense else sparse
            out.append(P @ self.d.geom_xmat[gi].reshape(3, 3).T + self.d.geom_xpos[gi])
            owner.append(np.full(len(P), self.m.geom_bodyid[gi]))
        return np.concatenate(out), np.concatenate(owner)


def fit_arm(sampler: ArmSampler, tree: cKDTree, seed_xyz, verbose_name: str):
    """p = [rotvec(3), t(3), q(7), g] → 모델 점 ↔ STL 최근접 거리 최소화 (2단계).

    한 번에 다 풀면 베이스 기울기와 관절각이 서로 보상하는 엉뚱한 해로 빠짐 (실측: 베이스 42° 기울어짐).
      1단계: 베이스는 수직(roll=pitch=0) 가정, link2·link3 점으로 [yaw, x, y, z, q1]
      2단계: 베이스는 ±3°/±6mm 안에서만 미세 조정, 나머지 관절·그리퍼 전부
    WeGo CAD 의 팔에는 base_link·link1 형상이 없음 (link2 부터 있음) → 정합에서 제외.
    """
    lim = sampler.m.jnt_range[:7]

    def resid_full(p, mask=None):
        R = Rotation.from_rotvec(p[:3]).as_matrix()
        P, _ = sampler.points(p[6:13], p[13])
        P = P[used if mask is None else mask]
        dist, _ = tree.query(P @ R.T + p[3:6], distance_upper_bound=0.05)
        return np.minimum(dist, 0.05)

    _, owner = sampler.points(np.zeros(7), 0.0)
    used = np.isin(owner, [sampler.m.body(n).id for n in ("base_link", "link1")], invert=True)
    mask1 = np.isin(owner, [sampler.m.body(n).id for n in ("link2", "link3")])

    def to_full(s):                                    # s = [yaw, x, y, z, q1]
        return np.r_[0, 0, s[0], s[1:4], s[4], np.zeros(6), 0.01]

    best = None
    for yaw in np.radians(np.arange(-157.5, 180, 45)):
        s0 = np.r_[yaw, seed_xyz, 0.0]
        r = least_squares(lambda s: resid_full(to_full(s), mask1), s0, loss="soft_l1", f_scale=0.002,
                          max_nfev=80, bounds=(np.r_[-np.pi, np.asarray(seed_xyz) - 0.1, lim[0, 0]],
                                               np.r_[np.pi, np.asarray(seed_xyz) + 0.1, lim[0, 1]]))
        med = float(np.median(resid_full(to_full(r.x), mask1)))
        if best is None or med < best[1]:
            best = (r.x, med)
    print(f"  {verbose_name} 1단계(베이스): yaw {np.degrees(best[0][0]):6.1f}°  xyz {np.round(best[0][1:4], 4)}  "
          f"q1 {best[0][4]:+.3f}  median {best[1] * 1000:.2f} mm")

    p0 = to_full(best[0])
    tol_r, tol_t = np.radians(3), 0.006
    lb = np.r_[p0[:3] - tol_r, p0[3:6] - tol_t, lim[:, 0], 0.0]
    ub = np.r_[p0[:3] + tol_r, p0[3:6] + tol_t, lim[:, 1], 0.05]
    p0 = np.clip(p0, lb + 1e-6, ub - 1e-6)
    r = least_squares(resid_full, p0, loss="soft_l1", f_scale=0.002, max_nfev=300, bounds=(lb, ub))
    return r.x, resid_full(r.x)


